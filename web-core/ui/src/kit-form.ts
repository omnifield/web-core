// ФОРМА КАРТЫ — то, чем рисуется каждая часть паспорта (`PWEB-84`, страница «Паспорт
// компонента», раздел «Кит отдаёт карту компонентов рядом с паспортами»).
//
// ## Зачем карта живёт у поставщика
//
// Паспорта кит централизует (`PASSPORTS`), а компоненты — нет. Механика сборки адресует части
// через точку (`accordion.control`), кит отдаёт плоские имена (`AccordionControl`).
// Совпадения нет ни по одной части, кроме корня, и собрать карту предлагалось каждому
// потребителю самому.
//
// Собрать её у себя потребитель может за три строки — и именно поэтому не должен: двадцать
// потребителей напишут двадцать карт, и ни одну из них никто не сверит с паспортом. Добавит кит
// шестую часть — она молча останется неодетой у всех. Расхождение обязано ловиться У НАС один
// раз, а не у каждого потребителя порознь и с опозданием.
//
// ## Карта и паспорт — ОДНО значение, а не два перечня рядом
//
// Отдай мы карту отдельным перечнем возле `PASSPORTS` — задвоение вернулось бы с другой стороны:
// два списка у поставщика расходятся ровно так же, как список у поставщика и список у
// потребителя. Поэтому наружу уезжает ПАРА: паспорт вместе с тем, чем рисуется каждая его часть.
// Взять карту без паспорта нечем — её отдельного экспорта не существует.
//
// Обратная сторона пары остаётся доступной подпутём `./passport`, и это не забывчивость.
// Значения карты — компоненты Solid, а подпуть паспорта продан как ДАННЫЕ, читаемые без Solid и
// без браузера: по нему ходят порождение CSS, проверка дерева и хранилище — всё, что живёт в
// Node, где `@kobalte/core` падает на первом же импорте. Затащи мы туда компоненты — сломались
// бы все три. Направление запрета выбрано по опасности: карта без паспорта порождает вторую
// карту, паспорт без карты не порождает ничего — из паспорта компонент не выводится.
//
// ## Своего перечня частей у карты нет
//
// Ключи карты не объявляются — они СВЕРЯЮТСЯ с анатомией, и сверяются дважды: типом при
// написании и `defineKitComponent` на исполнении. Второе не дублирует первое: поставщик вправе
// приехать сборкой без TypeScript, и тогда между «забыл часть» и молча неодетым узлом у
// потребителя не стоит ничего. Ровно этим же доводом закрыт перечень групп в форме паспорта
// (`@web-core/skin/model`, `PWEB-110`).

import type { ComponentPassport } from "@web-core/skin/model";

/**
 * Компонент, которым рисуется часть.
 *
 * Тип нарочно широкий — «любая функция», а не `Component<Props>`. Компоненты кита обобщены по
 * своему элементу (`slotAware` поверх `ValidComponent`: кнопка бывает `button`, `a` и чем угодно
 * ещё), и узкая подпись отвергла бы половину карты. Что именно лежит по адресу, решает тот, кто
 * рисует, — так же устроена и карта механики сборки (`ComponentMap`, значения `unknown`).
 *
 * Предмет карты — КЛЮЧИ: они обязаны совпасть с частями паспорта. Значения проверяются ровно на
 * то, что их можно позвать.
 */
export type PartComponent = (...args: never[]) => unknown;

/**
 * Компонент кита целиком: чем он себя объявил и чем рисуется каждая его часть.
 *
 * Пара, а не два поля рядом по случайности: это и есть форма, в которой карту нельзя взять без
 * паспорта. Ключи `parts` — части `passport.anatomy`, и тип `Part` у обоих полей один.
 */
export interface KitComponent<Part extends string = string> {
  /** Что компонент объявил о себе. Тот же паспорт, что уезжает подпутём `./passport`. */
  readonly passport: ComponentPassport<Part>;
  /** Чем рисуется каждая часть. Ключи — части паспорта, ни одной своей. */
  readonly parts: Readonly<Record<Part, PartComponent>>;
  /**
   * Невидимый провайдер (`PWEB-153`) — оборачивает корень для компонентов вроде поповера/меню,
   * чей корень (`positioner`) не рисует настоящего DOM-узла: `<Popover>`/`<Menu>` сами ничего не
   * рисуют, только раздают контекст вниз. Без обёртки та часть падает при попытке прочитать
   * контекст. Отсутствует у компонентов, чей корень уже реальный узел.
   */
  readonly provider?: PartComponent;
}

/**
 * Складывает паспорт с картой его частей и сверяет ключи с анатомией.
 *
 * Сверка здесь, а не у читателя: правило одно на всех, а написанное вторым читателем
 * разъезжается с написанным первым молча — оба будут зелёными. По той же причине рядом с формой
 * живут `admits` и `groupOf`.
 *
 * Отказ называет ЧАСТЬ, а не «карта неверна»: недостача обязана читаться без раскопок, иначе
 * проба краснеет там, где чинить нечего.
 *
 * @param passport паспорт компонента — источник перечня частей
 * @param parts чем рисуется каждая часть; ключи сверяются с анатомией
 * @param provider невидимый провайдер, оборачивающий корень (`PWEB-153`) — только у компонентов,
 *   чей корень не рисует настоящего DOM-узла; проверяется только то, что его можно позвать
 */
export function defineKitComponent<Part extends string>(
  passport: ComponentPassport<Part>,
  parts: Readonly<Record<Part, PartComponent>>,
  provider?: PartComponent,
): KitComponent<Part> {
  const declared = passport.anatomy.keys();
  const named = Object.keys(parts);

  const missing = declared.filter((part) => !Object.hasOwn(parts, part));
  if (missing.length > 0) {
    throw new Error(
      `карта «${passport.component}» не называет компонент для частей: ${missing.join(", ")}`,
    );
  }

  // Лишнее — не безобидная добавка: часть, которой в анатомии нет, не адресуема ничем, и
  // потребитель, увидевший её в карте, будет искать в паспорте то, чего там никогда не было.
  const unknown = named.filter((part) => !declared.includes(part as Part));
  if (unknown.length > 0) {
    throw new Error(
      `карта «${passport.component}» называет части, которых нет в паспорте: ${unknown.join(", ")}`,
    );
  }

  // Значение, которое нельзя позвать, отрисовка молча заменит запасным видом — то есть часть
  // окажется неодетой ровно так же, как если бы её в карте не было вовсе.
  const dead = declared.filter((part) => typeof parts[part] !== "function");
  if (dead.length > 0) {
    throw new Error(
      `в карте «${passport.component}» части названы не компонентом: ${dead.join(", ")}`,
    );
  }

  if (provider !== undefined && typeof provider !== "function") {
    throw new Error(`провайдер «${passport.component}» назван не компонентом`);
  }

  return { passport, parts, ...(provider ? { provider } : {}) };
}
