import solid from "vite-plugin-solid";
import { defineConfig } from "vitest/config";

// Три проекта, потому что пробы зоны живут в разных мирах и одним конфигом не покрываются:
//
//   • dom   — отрисовка на СВОИХ компонентах: дерево монтируется в НАСТОЯЩИЙ документ и
//     проверяется по узлам. Свои компоненты здесь не упрощение, а предмет: проверяется
//     механика, а не кит. Нужны JSDOM, JSX-трансформ и условия разрешения
//     `development`/`browser` — без них `solid-js/web` отдаёт СЕРВЕРНУЮ сборку и `render()`
//     падает «Client-only API called on the server side» (та же развилка и то же решение у зон
//     `ui` и `runtime`);
//   • kit   — та же отрисовка, но на ЖИВОМ ките: настоящая кнопка, настоящий паспорт, настоящее
//     правило допуска. Отдельным проектом из-за конвейера (см. ниже), а не из-за предмета;
//   • model — модель, правила и правки: ни документа, ни JSX там нет вовсе, и поднимать под них
//     браузерное окружение значило бы проверять не то, чем эта половина является. Она обязана
//     работать там, где документа нет, — подпуть `./model` ровно об этом.
//
// Пресет `@web-core/build/vitest` сюда НЕ подключается: он собран под ОДИН проект,
// а у зоны их три с разными окружениями и конвейерами (см. выше) — пресет решал бы не ту
// задачу. Зона `assembly` вполне зависит от `build` для сборки (`vite.config.ts`,
// `defineLibraryConfig`) — это уже не табу.

/** Общее для обоих браузерных проектов. */
const browser = {
  plugins: [solid()],
  resolve: { conditions: ["development", "browser"] },
};

export default defineConfig({
  test: {
    projects: [
      {
        ...browser,
        test: {
          name: "dom",
          environment: "jsdom",
          include: ["test/*.test.tsx"],
          // Пробы на живом ките отобраны ИМЕНЕМ (`kit*`), а не перечнем файлов: перечень
          // пришлось бы дописывать на каждой новой пробе, и забытая строка молча уехала бы в
          // проект, чей конвейер чужой JSX не преобразует.
          exclude: ["test/kit*.test.tsx"],
        },
      },
      {
        ...browser,
        test: {
          name: "kit",
          environment: "jsdom",
          include: ["test/kit*.test.tsx"],
          // Кит и его основания приезжают веткой `solid` — НЕпреобразованным JSX. Это их
          // обещание потребителю, а не недосмотр: трансформация Solid компиляторная, и
          // применяет её тот, кто собирает приложение. Значит применяем её и мы, иначе проба
          // спотыкается о расширение `.jsx` в чужих файлах.
          //
          // Правило общее (весь чужой код идёт через наш конвейер), а не перечень имён:
          // перечень пришлось бы дописывать на каждом уровне чужих зависимостей — за китом их
          // оказалось четыре, и каждый следующий открывался только падением. Заперто в
          // ОТДЕЛЬНЫЙ проект ровно поэтому: сквозная трансформация чужого кода касается только
          // той пробы, которой она нужна, и не удорожает остальные.
          server: { deps: { inline: true } },
        },
      },
      {
        test: {
          name: "model",
          environment: "node",
          include: ["test/*.test.ts"],
        },
      },
    ],
  },
});
