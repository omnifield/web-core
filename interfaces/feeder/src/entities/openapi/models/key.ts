import type { OpenapiEndpoint } from "./types.js";

/** Айди ручки — метод+url, а не индекс в списке и не `crypto.randomUUID()`: по этому айди на
 *  ручку ссылается привязка к компоненту, и она обязана пережить перезалив того же документа
 *  (перераспознавание даёт НОВЫЙ массив объектов, порядок и ссылки не сохраняются). Метод+url —
 *  то единственное, что документ несёт стабильно и что одинаково есть у распознанной ручки и у
 *  заведённой руками. */
export function endpointKey(endpoint: OpenapiEndpoint): string {
  return `${endpoint.method} ${endpoint.url}`;
}
