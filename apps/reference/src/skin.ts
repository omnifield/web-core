// СКИН ЭТАЛОНА — то, чем одета эта страница, и единственный источник её вида.
//
// ## Зачем он появился (ступень 2 роадмапа)
//
// До сих пор оформление брало значения из общего листа зоны значений: скругления и длительности
// приезжали `--radius-md`, `--motion-fast` и роднёй. Покрасить они ничего не могли, но это был
// ВТОРОЙ ПУТЬ к тому же результату — значение приходило в приложение мимо скина. Человек,
// собравший вид в редакторе, увидел бы у себя не то, что показывает эталон, а расхождение
// всплыло бы у него, а не у нас.
//
// Поэтому здесь скин, а не набор переменных. Половин у скина не бывает: он объявляет и значения
// (переменные), и вид (рецепт кнопки) — обе половины одной записью, той же механикой, которой
// скин собирает человек.
//
// ## Он МИНИМАЛЬНЫЙ и НАШ СОБСТВЕННЫЙ
//
// Это не эталонный скин фреймворка (он придёт ступенью 5 и заберёт отсюда всё, что окажется
// общим) и не продуктовый: те принадлежат другим владельцам. Здесь ровно то, что нужно ЭТОЙ
// странице, — и ни одного значения сверх.
//
// ## Почему имена значений свои, а не ступени напрямую
//
// Ступени скина (`--radius-md`) называются так же, как ступени общего листа: имена задаёт зона
// значений, и они одни на оба поставщика. Ссылайся оформление прямо на ступень — при снятом
// скине то же имя приехало бы листом, вид бы уцелел, и «значение приходит скином» осталось бы
// непроверяемым: сними скин, и ничего бы не изменилось.
//
// Поэтому оформление адресует ИМЕНА СКИНА (`--app-round`), а скин выводит их из своих ступеней.
// Снят скин — имени нет вовсе, и вид уходит целиком. Это и есть машинная разница между «вид от
// скина» и «вид сбоку».

import { withPassports, type Skin } from "@web-core/skin";
import { makeSkinSwitch, type SkinSwitch } from "@web-core/skin/wear";
import { passportOf } from "@web-core/ui/passport";

// Источник паспортов называется ОДИН РАЗ на файл и дальше едет связкой: у связанных
// вызовов довода для второго источника нет, и разойтись проверке с порождением нечем.
const { generateSkinCss } = withPassports(passportOf);

/**
 * Скин страницы: семя скруглений, имена для оформления и вид кнопки.
 *
 * Цвета здесь нет ни одного, и это не пробел: цвет — решение автора скина, а эталон проверяет
 * шов, а не вкус. Голая страница остаётся голой по цвету и одетой по форме.
 */
export const REFERENCE_SKIN: Skin = {
  name: "reference",
  variables: {
    // ПОСЕЯНО, а не выписано ступенями: назвал семя — получил всю лестницу. Значение то же, что
    // общий лист подставлял запасным, поэтому страница выглядит ровно как до перехода; пересев
    // семени двигает все скругления разом, и в этом весь смысл семени.
    //
    // Плотность не названа намеренно: шкала скруглений ею не масштабируется (`density: false` в
    // объявлении шкалы), а называть семя, которое ни в одну ступень не входит, значило бы завести
    // значение без потребителя.
    dimensions: { radius: "0.5rem" },
    light: {
      // Скругления — из СВОИХ ступеней, а не литералами: значение остаётся под семенем.
      "app-round": "var(--radius-md)",
      "app-round-item": "var(--radius-sm)",
      "app-round-ring": "var(--radius-full)",

      // ДВИЖЕНИЕ — ВРЕМЕННО ЗДЕСЬ И ЛИТЕРАЛАМИ.
      //
      // Длительности и кривые — ряд без семени: посеять его нечем, значит и пересеять нельзя,
      // значит это не шкала, и механика скина таких не печатает. Путь литералов для них объявлен
      // опорным и законен, но общими эти значения не становятся: ряд принадлежит ЭТАЛОННОМУ скину
      // и уедет туда на ступени 5. Тянуть их из общего листа (`--motion-fast`) нельзя — это ровно
      // тот второй путь, ради снятия которого всё и делается.
      //
      // Значения — те же, что вёз лист: страница обязана выглядеть как до перехода.
      "app-fade": "200ms",
      "app-fade-ease": "cubic-bezier(0, 0, 0.2, 1)",
      "app-spin-time": "400ms",
      "app-spin-ease": "linear",
    },
  },
  recipes: {
    // Кнопка — единственный компонент кита с паспортом, то есть единственный, чей вид сегодня
    // выразим рецептом. Остальные примитивы паспорта ещё не имеют и скинов не имеют вовсе: их
    // раскладывает оформление потребителя по зацепкам, и переедут они той же волной, что и
    // паспорта. Вид здесь — тот же, что оформление держало для кнопки до перехода.
    button: {
      base: {
        root: {
          props: {
            display: "inline-flex",
            alignItems: "center",
            justifyContent: "center",
            gap: "0.5rem",
            padding: "0.5rem 0.875rem",
            borderRadius: "var(--app-round)",
            font: "inherit",
            cursor: "pointer",
            transition: "opacity var(--app-fade) var(--app-fade-ease)",
          },
          states: {
            // Отключённая кнопка объявляет себя атрибутом — состояние из паспорта, а не
            // догадка по `:disabled`: паспорт для того и объявляет его, чтобы адрес был один.
            disabled: { props: { opacity: "0.5", cursor: "default" } },
          },
        },
      },
    },
  },
};

/**
 * Источник скинов приложения: одно имя, и текст порождается механикой скина из записи выше.
 *
 * Файла с адресом на этом пути нет ни на одном шаге — ровно как у приложения, берущего скины из
 * хранилища: там запись отдаёт служба, здесь она лежит рядом, а порождает CSS в обоих случаях
 * один и тот же генератор. Эталон обязан ходить той же дорогой, что человек.
 */
const SOURCE = {
  names: (): readonly string[] => [REFERENCE_SKIN.name],
  css: (name: string): string => {
    if (name !== REFERENCE_SKIN.name) {
      throw new Error(`[reference] скина «${name}» здесь нет — надевать нечего`);
    }
    return generateSkinCss(REFERENCE_SKIN);
  },
};

/**
 * Одевает страницу: заводит переключатель и надевает единственный скин.
 *
 * `remember: false` — выбор человека тут не участвует: это одежда приложения, а не то, что
 * выбрали в интерфейсе. Запомни мы его, приложение заняло бы человеку ключ хранилища под
 * решение, которого он не принимал.
 *
 * @returns переключатель — им же скин и снимают, когда проверяют, что вид приходит скином
 */
export function dressApp(): SkinSwitch {
  const skins = makeSkinSwitch(SOURCE);
  void skins.wear(REFERENCE_SKIN.name, { remember: false });
  return skins;
}
