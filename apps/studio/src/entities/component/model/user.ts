import { defineUserKind } from "@web-core/feeder";

/**
 * Компонент как участник связи с источником данных.
 *
 * Путь собирает построитель, а не мы: вид участника объявляется один раз и живёт в общем реестре
 * `@web-core/feeder` — там же, где адаптеры этими путями ищут друг друга. Собранный руками массив
 * промахнулся бы молча: поиск просто не нашёл бы связь и никто бы не сказал ни слова.
 *
 * Объявлен здесь, потому что строится из имени компонента — это знание о компоненте, а не о том,
 * кто его сегодня кормит.
 */
export const COMPONENT_USER = defineUserKind(
  "component",
  (name: string) => [name],
);
