/** Позиция на плоскости: столбец — шаг по primary-оси, строка — по secondary. */
export interface PlanePosition {
  readonly column: number;
  readonly row: number;
}

/**
 * Ближайшая точка привязки по одной оси.
 *
 * Плоскость — обычный скролл-контейнер с `scroll-snap-type: both mandatory`, поэтому «где мы
 * сейчас» — это не отдельное состояние, а арифметика от `scrollLeft`/`scrollTop`: рамки ровно
 * по размеру вьюпорта, значит индекс = смещение, делённое на размер. Округление, а не пол:
 * докрутили на 60% — значит уже следующая.
 *
 * Размер бывает нулевым (элемент ещё не разложен) — тогда делить не на что, и единственный
 * осмысленный ответ «первая», а не `NaN`, который потом молча уедет в `scrollTo`.
 */
export function snapIndexAt(
  scroll: number,
  size: number,
  count: number,
): number {
  if (size <= 0 || count <= 0) return 0;
  return Math.min(Math.max(Math.round(scroll / size), 0), count - 1);
}

/**
 * Живёт ли рамка (`index`) в окне вокруг текущей (`current`).
 *
 * Здесь всё, ради чего затевалась плоскость. Рамок на экране N×M, и это нормально — пустой div
 * ничего не стоит. А вот РЕНДЕР компонента через движок сборки стоит дорого, и N×M живых
 * рендеров — ровно то, что роняло браузер в прошлых заходах. Поэтому «слайд существует» и
 * «компонент отрисован» — разные вещи: рамки все, живых — окно.
 *
 * Радиус 1, а не 0: сосед обязан быть готов ДО того, как палец до него доедет, иначе свайп
 * показывает пустоту и дорисовывает после остановки.
 */
export function withinWindow(
  index: number,
  current: number,
  radius = 1,
): boolean {
  return Math.abs(index - current) <= radius;
}
