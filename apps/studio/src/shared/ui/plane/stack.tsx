import type { JSX } from "solid-js";
import type { NativeStyle } from "@web-core/skin";

const STACK = {
  position: "relative",
  display: "grid",
} as const satisfies NativeStyle;

/**
 * Общая коробка для плоскости и её линеек: плоскость занимает коробку целиком, линейки лежат
 * ПОВЕРХ неё.
 *
 * Линейки намеренно не стоят в потоке рядом с плоскостью. Стоя в потоке, они забирают себе
 * ширину и высоту, и дальше расходится всё: горизонтальная линейка центрируется по строке
 * вместе с вертикальной, а не по самой плоскости; плоскость сужается на ширину вертикальной
 * линейки; её собственные полосы прокрутки уезжают от края коробки. Поверх — линейка не занимает
 * места вовсе, и плоскость остаётся ровно той, что ей отвели.
 *
 * Поверх, но НЕ внутри скроллера: абсолютное позиционирование внутри прокручиваемого контейнера
 * едет вместе с содержимым. Линейки — соседи плоскости в этой коробке, поэтому стоят на месте.
 */
export function PlaneStack(props: {
  children: JSX.Element;
  style?: NativeStyle;
}) {
  return <div style={{ ...STACK, ...props.style }}>{props.children}</div>;
}
